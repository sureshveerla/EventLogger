uint32_t nmsCRC32::get (const void* buf, size_t len)
{

  uint32_t uiCRC32 = 0^0xFFFFFFFF;

  const uint8_t* u = static_cast<const uint8_t*>(buf);

  for (size_t i = 0; i < len; ++i)
  {
   uiCRC32 = aruiTable[(uiCRC32 ^ u[i])&0xFF] ^ (uiCRC32 >> 8);
  }

  return uiCRC32 ^ 0xFFFFFFFF;
}

bool nmsCRC32::verify (const void* buf, size_t len, uint32_t uiCRCIn)
{
  bool ocBRCode = true;

  uint32_t uiCRC32 = get (buf, len);

//  qDebug () << uiCRC32 << uiCRCIn;

  if (uiCRCIn != uiCRC32)
  {
   ocBRCode = false;
  }

  return ocBRCode;
}




